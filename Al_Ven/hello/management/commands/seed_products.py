class Command(BaseCommand):
    help = 'Добавляет в каталог демонстрационные товары (повторный запуск безопасен).'

    def handle(self, *args, **options):
        created_total = 0
        for category_name, items in PRODUCTS.items():
            category, _ = Category.objects.get_or_create(
                name=category_name,
                defaults={'coment': CATEGORY_DESCRIPTIONS[category_name]},
            )
            created = 0
            for name, sale, material, date_prod, conter, description in items:
                _, was_created = Products.objects.get_or_create(
                    name=name,
                    cat_id=category,
                    defaults={
                        'sale': sale,
                        'material': material,
                        'date_prod': date_prod,
                        'conter': conter,
                        'description': description,
                    },
                )
                created += was_created
            created_total += created
            self.stdout.write(f'{category_name}: добавлено {created} из {len(items)}')
        self.stdout.write(self.style.SUCCESS(
            f'Готово. Новых товаров: {created_total}, всего в каталоге: {Products.objects.count()}'
        ))
